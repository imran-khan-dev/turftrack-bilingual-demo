export function getValidationMessageMatch(
  message: string,
): ValidationMessageMatch | null {
  const maxPeriods = message.match(/^Maximum (\d+) periods per day$/);
  if (maxPeriods) {
    return { key: "maximumPeriodsPerDay", values: { count: Number(maxPeriods[1]) } };
  }

  const key = validationMessageKeys[message];
  return key ? { key } : null;
}
